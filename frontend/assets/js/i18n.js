let currentLang = null;

export function detectLang() {
  const saved = localStorage.getItem('pandaviz.lang');
  if (saved === 'zh' || saved === 'en') return saved;
  const nav = (navigator.language || 'zh').toLowerCase();
  return nav.startsWith('zh') ? 'zh' : 'en';
}

export function getLang() {
  if (!currentLang) currentLang = detectLang();
  return currentLang;
}

export function setLang(lang) {
  currentLang = lang === 'en' ? 'en' : 'zh';
  localStorage.setItem('pandaviz.lang', currentLang);
  document.documentElement.lang = currentLang === 'zh' ? 'zh' : 'en';
  return currentLang;
}

/** 取词条并按 {var} 插值 */
export function t(key, vars) {
  const lang = getLang();
  const table = MESSAGES[lang] || MESSAGES.zh;
  let text = table[key];
  if (text === undefined) text = (MESSAGES.zh[key] !== undefined ? MESSAGES.zh[key] : key);
  if (vars) {
    text = String(text).replace(/\{(\w+)\}/g, (match, name) =>
      Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match);
  }
  return text;
}

/** 处理后端返回的 {zh, en} 双语对象 */
export function localize(obj, fallback) {
  if (obj === null || obj === undefined) return fallback !== undefined ? fallback : '—';
  if (typeof obj === 'string') return obj;
  const lang = getLang();
  return obj[lang] !== undefined ? obj[lang] : (obj.zh !== undefined ? obj.zh : (obj.en !== undefined ? obj.en : (fallback || '—')));
}

/** 列的中英文名称 */
export function columnLabel(columnMeta, name) {
  if (columnMeta && columnMeta.label) return localize(columnMeta.label, name);
  return name === null || name === undefined ? '—' : String(name);
}

/** 类别取值的双语显示（底层数据值保持不变）
 * 后端 value_labels 有两种形态：{值: 英文名} 或 {值: {zh, en}}，都要正确处理。 */
export function valueLabel(columnMeta, value) {
  if (value === null || value === undefined) return '∅';
  if (columnMeta && columnMeta.value_labels) {
    const mapped = columnMeta.value_labels[value];
    if (typeof mapped === 'string') return getLang() === 'en' ? mapped : String(value);
    if (mapped) return localize(mapped, String(value));
  }
  return String(value);
}

/** 图表类型名称 */
export function chartTypeLabel(typeName) {
  const entry = CHART_TYPE_LABELS[typeName];
  if (!entry) return typeName;
  return localize(entry, typeName);
}

export function chartChannels(typeName) {
  return CHART_CHANNELS[typeName] || CHART_CHANNELS.bar;
}

export function applyStaticTranslations(root) {
  const scope = root || document;
  scope.querySelectorAll('[data-i18n]').forEach((node) => {
    node.textContent = t(node.getAttribute('data-i18n'));
  });
  scope.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    node.setAttribute('placeholder', t(node.getAttribute('data-i18n-placeholder')));
  });
  scope.querySelectorAll('[data-i18n-title]').forEach((node) => {
    node.setAttribute('title', t(node.getAttribute('data-i18n-title')));
  });
}
